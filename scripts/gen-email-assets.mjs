// Regenerates src/backend/lib/emailAssets.ts from public/email/*.png.
// Run after changing any email logo/hero image:  node scripts/gen-email-assets.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, basename } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const dir = join(root, "public", "email");
const items = [["rj-logo", join(dir, "logo.png")]];
for (const f of readdirSync(join(dir, "hero")).filter((n) => n.endsWith(".png")).sort()) {
  items.push([`rj-hero-${basename(f, ".png")}`, join(dir, "hero", f)]);
}
const out = [
  "/* AUTO-GENERATED by scripts/gen-email-assets.mjs from public/email/*.png — do not edit by hand.",
  " * Base64 PNGs attached to outgoing emails as inline (cid:) images, so they display even when",
  " * NEXT_PUBLIC_APP_URL is unset, points at localhost, or the site hasn't deployed public/email/. */",
  "export const EMAIL_ASSETS: Record<string, string> = {",
  ...items.map(([cid, p]) => `  "${cid}": "${readFileSync(p).toString("base64")}",`),
  "};",
  "",
].join("\n");
writeFileSync(join(root, "src", "backend", "lib", "emailAssets.ts"), out);
console.log(`Wrote ${items.length} assets to src/backend/lib/emailAssets.ts`);
